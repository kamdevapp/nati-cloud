def render(code: str, params: dict | None = None) -> str:
    """Tekst angielski komunikatu z wstawionymi parametrami (nieznany kod – sam kod)."""
    template = MESSAGES.get(code, code)
    try:
        return template.format(**(params or {}))
    except (KeyError, IndexError, ValueError):
        return template
